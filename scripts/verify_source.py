#!/usr/bin/env python3
"""Fast repository consistency checks; deliberately not a replacement for Dart/SQL tests."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
errors: list[str] = []

def read(path: str) -> str:
    p = ROOT / path
    if not p.is_file():
        errors.append(f"Missing required file: {path}")
        return ""
    return p.read_text(encoding="utf-8")

migration = read("supabase/migrations/20261024000100_pocketcloud_core.sql")
legal = read("lib/core/legal_versions.dart")
readme = read("README.md")
workflow = read(".github/workflows/android-apk.yml")
edge_pair = read("supabase/functions/redeem-pairing/index.ts")
edge_revoke = read("supabase/functions/revoke-device/index.ts")
onboarding = read("lib/features/onboarding/onboarding_screen.dart")
transfer = read("lib/services/webrtc_transfer_service.dart")

required_tables = ["profiles", "user_consents", "devices", "pairing_codes", "device_pairs", "signaling_messages", "connection_events"]
for table in required_tables:
    if not re.search(rf"alter table public\.{table} enable row level security", migration, re.I):
        errors.append(f"RLS is not enabled for public.{table}")

for policy in ["terms", "privacy"]:
    version = re.search(rf"static const {policy} = '([^']+)'", legal)
    if not version:
        errors.append(f"Could not read {policy} version from legal_versions.dart")
    elif f"c.policy_version = '{version.group(1)}'" not in migration:
        errors.append(f"SQL consent gate version does not match {policy} version {version.group(1)}")

if not re.search(r"revoke\s+insert,\s*update\s+on public\.device_pairs from authenticated", migration, re.I):
    errors.append("Authenticated clients must not insert/update device_pairs directly")
if not re.search(r"grant execute on function public\.redeem_pairing_code_atomic\(uuid, text, uuid\) to service_role", migration, re.I):
    errors.append("Pair redemption RPC is not restricted to the service-role execution path")
if not re.search(r"grant execute on function public\.revoke_device_atomic\(uuid, uuid\) to service_role", migration, re.I):
    errors.append("Device revocation RPC is not restricted to the service-role execution path")
if re.search(r"security\s+definer", migration, re.I):
    errors.append("Public migration unexpectedly contains SECURITY DEFINER")
for rpc in ("redeem_pairing_code_atomic", "revoke_device_atomic"):
    section = migration.split(f"function public.{rpc}", 1)
    if len(section) < 2 or "security invoker" not in section[1][:500].lower():
        errors.append(f"{rpc} must run as SECURITY INVOKER")
if not re.search(r"create trigger devices_stamp_activity before insert or update on public\.devices", migration, re.I):
    errors.append("Device activity timestamps must be database-stamped")
if "'status': 'pending'" in read("lib/features/devices/devices_screen.dart"):
    errors.append("Flutter insert must not set pairing_codes.status; rely on DB default")
if "decided_at': DateTime.now" in onboarding or "'decided_at': timestamp" in onboarding:
    errors.append("Consent timestamps must be generated by PostgreSQL")
if "_downloadWaiters.containsKey(requestId)" not in transfer:
    errors.append("Incoming downloads must match a request that is currently pending")
if "Automatic reconnect paused after 8 attempts" not in transfer:
    errors.append("Reconnect retry must remain bounded")
if "PolicyText.terms" not in onboarding or "PolicyText.privacy" not in onboarding:
    errors.append("Both full policy drafts must be reachable from onboarding")
if "--dart-define=SUPABASE_PUBLISHABLE_KEY" not in workflow:
    errors.append("Android workflow must pass the publishable key to the build")
if "return _isClientKey(supabasePublishableKey);" not in read("lib/core/app_config.dart"):
    errors.append("App config must validate Supabase client-key format")
if "uri.port != 443" not in read("lib/core/app_config.dart"):
    errors.append("Supabase config must reject custom URL ports")
if "Configure repository Actions Variables SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY" not in workflow:
    errors.append("APK workflow must fail clearly without live project config")
if re.search(r"SUPABASE_SERVICE_ROLE_KEY\s*=|sb_secret_[A-Za-z0-9]{20,}|eyJ[A-Za-z0-9_-]{100,}", "\n".join(p.read_text(errors="ignore") for p in (ROOT / "lib").rglob("*.dart")), re.I):
    errors.append("A server-only credential appears hardcoded in Dart source")
if re.search(r"FontWeight\.w750", "\n".join(p.read_text(errors="ignore") for p in (ROOT / "lib").rglob("*.dart"))):
    errors.append("Invalid FontWeight.w750 exists")

# Minimum docs should exist and explicitly warn about unverified runtime behaviour.
for doc in ["FEATURES.md", "ARCHITECTURE.md", "DATABASE.md", "SECURITY.md", "PRIVACY_POLICY.md", "TERMS.md", "UI_SPEC.md", "SETUP_SUPABASE.md", "TEST_PLAN.md", "QA_CHECKLIST.md", "KNOWN_LIMITATIONS.md"]:
    read(f"docs/{doc}")
if "not been compiled or executed with Flutter" not in readme:
    errors.append("README must disclose that Flutter runtime verification has not been performed")

if errors:
    print("PocketCloud source verification FAILED:")
    for error in errors:
        print(f" - {error}")
    sys.exit(1)

print("PocketCloud repository consistency checks passed.")
print("Note: this check does not compile Dart, parse/run the SQL migration, deploy Supabase or test real-device networking.")
