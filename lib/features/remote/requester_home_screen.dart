import 'dart:async';
import 'package:flutter/material.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

import '../../core/app_theme.dart';
import '../../services/device_repository.dart';
import '../devices/pairing_scanner_screen.dart';
import '../remote/remote_files_screen.dart';

class RequesterHomeScreen extends StatefulWidget {
  const RequesterHomeScreen({super.key});

  @override
  State<RequesterHomeScreen> createState() => _RequesterHomeScreenState();
}

class _RequesterHomeScreenState extends State<RequesterHomeScreen> {
  final _repo = DeviceRepository();
  List<Map<String, dynamic>> _pairedHosts = [];
  bool _loading = true;
  String? _error;
  String? _localDeviceId;

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    setState(() {
      _loading = true;
      _error = null;
    });

    try {
      final current = await _repo.ensureThisDevice();
      final pairs = await _repo.listPairs();
      final devices = await _repo.listDevices();
      final deviceMap = {for (var d in devices) d['id'].toString(): d};

      final hosts = <Map<String, dynamic>>[];
      for (final p in pairs) {
        final serverId = p['server_device_id']?.toString();
        if (serverId != null && deviceMap.containsKey(serverId)) {
          hosts.add({'pair': p, 'device': deviceMap[serverId]});
        }
      }

      if (mounted) {
        setState(() {
          _localDeviceId = current['id'];
          _pairedHosts = hosts;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() => _error = 'Could not load paired hosts.');
      }
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  Future<void> _connectWithCode() async {
    final controller = TextEditingController();
    final code = await showDialog<String>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: const Text('Connect to a host'),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              'Enter the 12-character pairing code generated by the host phone:',
            ),
            const SizedBox(height: 12),
            TextField(
              controller: controller,
              textCapitalization: TextCapitalization.characters,
              autocorrect: false,
              enableSuggestions: false,
              decoration: const InputDecoration(
                hintText: 'Enter 12-character code',
              ),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, null),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () =>
                Navigator.pop(dialogContext, controller.text.trim()),
            child: const Text('Redeem & Connect'),
          ),
        ],
      ),
    );
    controller.dispose();

    if (code == null || code.length != 12) return;
    if (!mounted) return;

    final messenger = ScaffoldMessenger.of(context);
    try {
      final localId = _localDeviceId;
      if (localId == null) throw StateError('This device is registering.');

      final result = await Supabase.instance.client.functions.invoke(
        'redeem-pairing',
        body: {'code': code, 'clientDeviceId': localId},
      );
      if (result.status < 200 || result.status >= 300) {
        throw StateError('Pairing code invalid or expired.');
      }
      if (mounted) {
        messenger.showSnackBar(
          const SnackBar(content: Text('Host paired successfully!')),
        );
        await _load();
      }
    } catch (e) {
      if (mounted) {
        messenger.showSnackBar(
          SnackBar(
            content: Text(
              'Failed: ${e is StateError ? e.message : 'Invalid code.'}',
            ),
          ),
        );
      }
    }
  }

  Future<void> _scanQr() async {
    final scannedCode = await Navigator.of(context).push<String>(
      MaterialPageRoute(builder: (_) => const PairingScannerScreen()),
    );
    if (scannedCode != null && scannedCode.isNotEmpty) {
      await _connectWithCode();
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Connect to Host'),
        actions: [
          IconButton(onPressed: _load, icon: const Icon(Icons.refresh_rounded)),
        ],
      ),
      body: RefreshIndicator(
        onRefresh: _load,
        child: ListView(
          padding: const EdgeInsets.all(20),
          children: [
            Text(
              'Request & Connect',
              style: Theme.of(context).textTheme.headlineMedium,
            ),
            const SizedBox(height: 8),
            Text(
              'Connect to a PocketCloud host phone to browse, download, or upload files directly over encrypted WebRTC.',
              style: Theme.of(
                context,
              ).textTheme.bodyMedium?.copyWith(color: AppColors.muted),
            ),
            const SizedBox(height: 20),
            Row(
              children: [
                Expanded(
                  child: FilledButton.icon(
                    onPressed: _scanQr,
                    icon: const Icon(Icons.qr_code_scanner_rounded),
                    label: const Text('Scan QR Code'),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: _connectWithCode,
                    icon: const Icon(Icons.pin_rounded),
                    label: const Text('Enter Code'),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 28),
            Text(
              'Paired Host Phones',
              style: Theme.of(context).textTheme.titleLarge,
            ),
            const SizedBox(height: 12),
            if (_loading)
              const Center(
                child: Padding(
                  padding: EdgeInsets.all(20),
                  child: CircularProgressIndicator(),
                ),
              )
            else if (_error != null)
              Text(_error!, style: const TextStyle(color: AppColors.danger))
            else if (_pairedHosts.isEmpty)
              Container(
                padding: const EdgeInsets.all(20),
                decoration: BoxDecoration(
                  color: AppColors.surface,
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(color: AppColors.border),
                ),
                child: const Text(
                  'No host phones paired yet. Tap Scan QR Code or Enter Code to pair with your host device.',
                ),
              )
            else
              ..._pairedHosts.map((item) {
                final device = item['device'] as Map<String, dynamic>;
                final lastSeen = DateTime.tryParse(
                  device['last_seen_at']?.toString() ?? '',
                );
                final fresh =
                    lastSeen != null &&
                    DateTime.now().toUtc().difference(lastSeen.toUtc()) <
                        const Duration(seconds: 90);
                final online =
                    device['server_enabled'] == true &&
                    fresh &&
                    device['revoked_at'] == null;

                return Container(
                  margin: const EdgeInsets.only(bottom: 12),
                  padding: const EdgeInsets.all(16),
                  decoration: BoxDecoration(
                    color: AppColors.surface,
                    borderRadius: BorderRadius.circular(18),
                    border: Border.all(color: AppColors.border),
                  ),
                  child: Row(
                    children: [
                      Icon(
                        Icons.dns_rounded,
                        color: online ? AppColors.accent : AppColors.muted,
                        size: 32,
                      ),
                      const SizedBox(width: 14),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              device['name']?.toString() ?? 'Host Phone',
                              style: const TextStyle(
                                fontWeight: FontWeight.w700,
                                fontSize: 16,
                              ),
                            ),
                            const SizedBox(height: 4),
                            Text(
                              online
                                  ? 'Online • Ready to connect'
                                  : 'Offline • Check host phone',
                              style: TextStyle(
                                fontSize: 12,
                                color: online
                                    ? AppColors.accent
                                    : AppColors.muted,
                              ),
                            ),
                          ],
                        ),
                      ),
                      FilledButton(
                        onPressed: () {
                          Navigator.of(context).push(
                            MaterialPageRoute(
                              builder: (_) => RemoteFilesScreen(
                                localDeviceId: _localDeviceId ?? '',
                                serverDeviceId: device['id'].toString(),
                              ),
                            ),
                          );
                        },
                        child: const Text('Connect'),
                      ),
                    ],
                  ),
                );
              }),
          ],
        ),
      ),
    );
  }
}
